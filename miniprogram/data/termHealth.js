// 「今天怎么喝」：按手机本地时间给一句，四个时段轮换。
// 不写水温、毫升数这类看着精确其实没依据的数字。
function drinkLine(hour) {
  const h = typeof hour === 'number' ? hour : new Date().getHours();
  if (h >= 5 && h < 10) return '早上先喝一杯温水再出门，胃里暖了人也醒得快。';
  if (h >= 10 && h < 14) return '中午配一碗热汤，别拿冰饮顶饭。';
  if (h >= 14 && h < 18) return '下午手边放杯温水，别等口渴才想起来喝。';
  return '晚上少碰冷饮和浓茶，温水小口喝。';
}

/**
 * @param {string} name 节气名
 * @param {object} opts { hour, daysToNext }
 * @returns {{climate: string, items: Array<{k: string, v: string}>}|null}
 */
function buildToday(name, opts) {
  const rec = TERM_HEALTH[name]
  if (!rec) return null

  const o = opts || {}
  const items = []

  // 今天：喝水提醒；正换节气（前后 3 天）时补一句天气易反复
  let today = drinkLine(o.hour)
  const days = typeof o.daysToNext === 'number' ? o.daysToNext : null
  if (days !== null && days >= 0 && days <= 3) {
    today += '这两天正换节气，天气容易反复，衣服别急着加减。'
  }
  items.push({ k: '今天', v: today })
  items.push({ k: '吃什么', v: rec.eat })
  items.push({ k: '起居', v: rec.live })

  return { climate: rec.climate, items }
}

// 兼容旧调用：只要气候特征与三条提醒，不带时间参数
function getHealth(name) {
  return buildToday(name, {})
}

